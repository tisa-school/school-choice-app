    def test_succession_once_per_visit_and_nojs_visibility(self):
        with sync_playwright() as p:
            browser,page=self.launch(p)
            page.goto(self.live_server_url+'/demo/')
            page.locator('[data-reveal="hero"]').wait_for()
            page.locator('.succession-enter').first.wait_for(state='attached')
            expect(page.locator('.succession-enter')).to_have_count(0)
            page.locator('nav [data-view="events"]').click()
            expect(page.locator('.succession-enter')).to_have_count(0)
            page.get_by_role('button',name='Clear all',exact=True).click()
            self.assertEqual(page.locator('.succession-enter').count(),0)
            page.locator('#language').select_option('pt')
            self.assertEqual(page.locator('.succession-enter').count(),0)
            page.emulate_media(reduced_motion='reduce')
            page.locator('nav [data-view="crews"]').click()
            self.assertEqual(page.locator('.succession-enter').count(),0)
            page.locator('#role').select_option('parent')
            page.locator('[data-view="onboarding"]').click()
            page.get_by_label('Inventa um PIN demo de quatro dígitos',exact=True).fill('2468')
            page.get_by_role('checkbox').check()
            page.get_by_role('button',name='Criar perfil demo',exact=True).click()
            expect(page.locator('h1')).to_contain_text('Uma nova cidade.')
            self.assertFalse('2468' in page.content())
            context=browser.new_context(java_script_enabled=False)
            plain=context.new_page();plain.goto(self.live_server_url+'/about/')
            self.assertTrue(plain.locator('.about-hero h1').is_visible())
            for node in plain.locator('[data-reveal]').all():
                self.assertEqual(node.evaluate("e=>getComputedStyle(e).opacity"),'1')
            context.close();browser.close()
