    def test_responsive_bilingual_keyboard_animation_and_screenshots(self):
        with sync_playwright() as p:
            browser,page=self.launch(p)
            errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
            pages=['home','child','events','detail','family','crews','calendar','organizer','creator','admin','safety','about','onboarding','saved']
            page.goto(self.live_server_url+'/demo/')
            for locale in ['en','pt-PT']:
                page.locator('#language').select_option(locale)
                page.wait_for_function('(code)=>document.documentElement.lang===code',arg=locale)
                for width in [360,390,768,1024,1440]:
                    page.set_viewport_size({'width':width,'height':1000})
                    for view in pages:
                        page.evaluate("([view])=>{const a=document.createElement('a');a.dataset.view=view;a.dataset.id=view==='detail'?'art-afternoon':'';a.href='#';document.body.append(a);a.click();a.remove();}",[view])
                        self.assertFalse(page.evaluate('document.documentElement.scrollWidth > innerWidth'),f'{locale}, {width}, {view}')
                        self.assertTrue(page.locator('h1').is_visible())
            page.locator('#language').select_option('en')
            page.wait_for_function('(code)=>document.documentElement.lang===code',arg='en')
            page.locator('#role').select_option('child')
            page.emulate_media(reduced_motion='reduce')
            page.locator('nav [data-view="events"]').click()
            self.assertEqual(page.locator('.succession-enter').count(),0)
            page.keyboard.press('Tab');self.assertTrue(page.evaluate("document.activeElement!==document.body"))
            page.get_by_label('Age',exact=True).select_option('11')
            page.get_by_label('Interest',exact=True).select_option('Arts')
            page.get_by_label('Area',exact=True).select_option('Alfama')
            page.locator('#filter-language').select_option('English')
            page.get_by_label('Price',exact=True).select_option('free')
            page.get_by_role('button',name='Apply filters',exact=True).click()
            expect(page.get_by_role('heading',name='1 activity to explore',exact=True)).to_be_visible()
            screenshots=Path(settings.BASE_DIR)/'docs/screenshots'
            page.screenshot(path=str(screenshots/'discover.png'),full_page=True)
            page.locator('[data-view="detail"][data-id="art-afternoon"]').first.click()
            page.screenshot(path=str(screenshots/'event-detail.png'),full_page=True)
            page.set_viewport_size({'width':390,'height':844})
            page.screenshot(path=str(screenshots/'event-detail-mobile.png'),full_page=True)
            page.locator('nav [data-view="about"]').click()
            for name in ['Sophia','Rosie','Daniel','Zehra Yilmaz','Lucas Alves','Artem Tolmachev','Karina Medvedeva','Anna Kupavtseva']:
                self.assertEqual(page.get_by_role('heading',name=name,exact=True).count(),1)
            # In-memory state cannot leak into another tab or survive reload.
            self.assertEqual(page.evaluate('localStorage.length'),0)
            self.assertEqual(errors,[])
